"""Tests du mode démonstration : python3 tests/test_management.py
Le dossier parent doit contenir grist-graphique (comme sur lab17bis.github.io).
Variables : CHROME (navigateur), URL (par défaut http://localhost:8780/grist-management/)."""
import os, sys
from playwright.sync_api import sync_playwright
URL = os.environ.get('URL', 'http://localhost:8780/grist-management/')
ok = ko = 0
def verifier(nom, cond):
    global ok, ko
    print(('OK   ' if cond else 'ÉCHEC ') + nom); ok += bool(cond); ko += (not cond)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ.get('CHROME') or None, args=['--no-sandbox'])
    pg = b.new_page(viewport={'width': 1400, 'height': 1000}); erreurs = []
    pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto(URL); pg.wait_for_selector('.mg-grille')
    # Version figée v1 : les modules de grist-graphique doivent se charger (régression 2026-11-26, chemin doublé).
    pv = b.new_page(); pv.goto(URL.rstrip('/') + '/v1/'); pv.wait_for_selector('.mg-grille')
    verifier('v1 : modules grist-graphique chargés', pv.evaluate('!!(window.Tableau && window.Donnees)')); pv.close()
    verifier('écrans automatiques du niveau Équipe (avec la charge)', pg.locator('[data-ecran]').count() == 4)
    verifier('badge du niveau Équipe', 'Équipe Accueil' in pg.locator('.mg-niveau').inner_text() or 'ÉQUIPE ACCUEIL' in pg.locator('.mg-niveau').inner_text().upper())
    # Priorités et points chauds : l'équipe Accueil voit les siennes et celles sans équipe, point chaud en tête
    verifier('priorités : 3 (Accueil et direction)', pg.locator('.mg-priorite').count() == 3)
    verifier('point chaud en tête', 'mg-priorite--chaud' in (pg.locator('.mg-priorite').first.get_attribute('class') or ''))
    verifier('priorité d\'une autre équipe absente', pg.get_by_text('Clôture des comptes').count() == 0)
    pg.locator('summary', has_text='Publier une priorité').click()
    pg.fill('[data-prio="Titre"]', 'Priorité de test'); pg.locator('form[data-form="priorite"] button[type="submit"]').click()
    verifier('publier une priorité', pg.locator('.mg-priorite', has_text='Priorité de test').count() == 1)
    pg.locator('.mg-priorite', has_text='Priorité de test').get_by_role('button', name='Retirer').click()
    verifier('retirer une priorité', pg.locator('.mg-priorite', has_text='Priorité de test').count() == 0)
    verifier('signalement d\'une autre équipe absent', pg.get_by_text('Priorité entre la campagne').count() == 0)
    verifier('chiffres clés', pg.locator('.mg-chiffre').count() >= 4)
    verifier('météo : 5 rubriques', pg.locator('.mg-meteo tbody tr').count() == 5)
    verifier('météo : cases critiques', pg.locator('.mg-meteo__case.mg-statut--rouge').count() >= 1)
    verifier('signalements ouverts : 3', pg.locator('.mg-signalement').count() == 3)
    verifier('signalement bloquant en tête', 'File d' in pg.locator('.mg-signalement__titre').first.inner_text())
    verifier('actions des deux outils', pg.locator('.mg-action__meta', has_text='Réunion').count() >= 1 and pg.locator('.mg-action__meta', has_text='Projet').count() >= 1)
    pg.locator('summary', has_text='Renseigner la météo').click()
    pg.locator('label[for="mt-4-0"]').click(); pg.get_by_role('button', name='Enregistrer la météo du jour').click()
    verifier('saisie de la météo du jour', pg.get_by_text('Météo du jour enregistrée').count() == 1)
    pg.locator('summary', has_text='Signaler un problème').click()
    pg.fill('#sg-titre', 'Problème de test'); pg.get_by_role('button', name='Signaler', exact=True).click()
    verifier('signaler un problème', pg.locator('.mg-signalement', has_text='Problème de test').count() == 1)
    pg.locator('.mg-signalement', has_text='Problème de test').get_by_role('button', name='Résoudre').click()
    pg.locator('.mg-signalement input[required]').fill('Corrigé'); pg.get_by_role('button', name='Marquer résolu').click()
    verifier('résoudre un signalement', pg.locator('.mg-signalement', has_text='Problème de test').count() == 0)
    # Charge vécue : répartition, raisons sans nom sauf choix de l'agent, jamais l'adresse
    pg.locator('[data-ecran="1"]').click(); pg.wait_for_timeout(300)
    rep = pg.locator('.mg-repartition').inner_text()
    verifier('charge : répartition 1 / 2 / 2', 'Confortable : 1 (20' in rep and 'Chargé : 2 (40' in rep and 'Débordé : 2 (40' in rep)
    txt = pg.locator('#mg-app').inner_text()
    verifier('charge : nom montré seulement si l\'agent l\'a choisi', '(Camille Martin)' in txt and 'p0' not in txt and 'p1' not in txt)
    pg.locator('summary', has_text='Donner ma charge').click(); pg.locator('label[for="ch-2"]').click()
    pg.fill('#ch-raison', 'Test de charge'); pg.locator('form[data-form="charge"] button[type="submit"]').click(); pg.wait_for_timeout(300)
    rep = pg.locator('.mg-repartition').inner_text()
    verifier('charge : ma réponse compte (une par semaine)', 'Débordé : 3' in rep and '6 réponses' in pg.locator('#mg-app').inner_text())
    pg.locator('summary', has_text='Donner ma charge').click(); pg.locator('label[for="ch-0"]').click(); pg.locator('form[data-form="charge"] button[type="submit"]').click(); pg.wait_for_timeout(300)
    rep = pg.locator('.mg-repartition').inner_text()
    verifier('charge : la nouvelle réponse remplace la précédente', 'Débordé : 2' in rep and 'Confortable : 2' in rep and '6 réponses' in pg.locator('#mg-app').inner_text())
    pg.locator('summary', has_text='Qualifier la tension').click(); pg.locator('label[for="te-2"]').click()
    pg.fill('#te-com', 'Tension de test'); pg.locator('form[data-form="tension"] button[type="submit"]').click(); pg.wait_for_timeout(300)
    verifier('qualifier la tension de la semaine', 'Tension critique' in pg.locator('.mg-tension').inner_text() and 'Tension de test' in pg.locator('.mg-tension').inner_text())
    pg.locator('[data-ecran="2"]').click(); pg.wait_for_timeout(300)
    verifier('écran projets et réunions', pg.locator('.mg-kanban__col').count() >= 5 and pg.locator('.mg-odj li').count() >= 1)
    pg.locator('[data-ecran="0"]').click(); pg.wait_for_timeout(300)
    pg.locator('summary', has_text='Noter une décision').click()
    pg.fill('#dc-int', 'Décision de test'); pg.fill('#dc-resp', 'Lou Petit'); pg.locator('form[data-form="decision"] button[type="submit"]').click(); pg.wait_for_timeout(300)
    verifier('décision du point d\'équipe notée comme action', pg.locator('.mg-zone--actions', has_text='Décision de test').count() == 1)
    pg.locator('[data-ecran="3"]').click(); pg.wait_for_selector('.tb-bloc', timeout=8000)
    verifier('tableau de bord grist-graphique intégré', pg.locator('.tb-bloc').count() >= 3)
    pg.screenshot(path='/tmp/mg-tableau.png')
    pg.locator('[data-ecran="0"]').click()
    pg.get_by_role('button', name='Mode affichage').click()
    verifier('mode affichage : saisie masquée', not pg.locator('.mg-saisie').first.is_visible())
    pg.screenshot(path='/tmp/mg-affichage.png', full_page=True)
    # Aperçu réel : l'outil lui-même, avec les réglages non enregistrés
    pg.goto(URL); pg.wait_for_selector('.mg-grille')
    pg.locator('.cl-barre label', has_text='Réglages').click(); pg.wait_for_selector('#rg-rub')
    pg.fill('#rg-rub', 'Rubrique brouillon\nQualité de service\nDélais\nMoyens\nÉquipe')
    pg.locator('.cl-barre label', has_text='Aperçu').click(); pg.wait_for_timeout(600)
    verifier('aperçu réel : l\'outil est dans le cadre de l\'aperçu', pg.locator('.cl-apercu #mg-app .mg-grille').count() == 1)
    verifier('aperçu réel : les réglages non enregistrés s\'appliquent', 'Rubrique brouillon' in pg.locator('.cl-apercu #mg-app').inner_text())
    pg.locator('.cl-barre .cl-onglets label', has_text='Réglages').click(); pg.wait_for_timeout(600)
    verifier('aperçu quitté : l\'outil est revenu dans son onglet, réglages enregistrés rétablis', pg.locator('.cl-apercu #mg-app').count() == 0 and 'Rubrique brouillon' not in pg.locator('#mg-app').inner_text())
    # Réglages : section des deux niveaux et choix du niveau de la vue
    pg.locator('.cl-barre .cl-onglets label', has_text='Réglages').click(); pg.wait_for_selector('#rg-eq')
    verifier('réglages : équipes listées', 'Accueil' in pg.input_value('#rg-eq') and 'Gestion' in pg.input_value('#rg-eq'))
    verifier('réglages : avertissement délégué à la protection des données', pg.get_by_text('délégué à la protection des données').count() >= 1)
    pg.locator('label[for="vue-niv-pilotage"]').click(); pg.get_by_role('button', name='Appliquer à cette vue').click(); pg.wait_for_timeout(500)
    pg.locator('.cl-barre label', has_text='Aperçu').click(); pg.wait_for_timeout(600)
    verifier('réglages : niveau Pilotage appliqué à la vue', 'PILOTAGE' in pg.locator('.mg-niveau').inner_text().upper() and pg.locator('.mg-zone--escalades').count() == 1)
    # Niveau Pilotage
    pp = b.new_page(viewport={'width': 1400, 'height': 1000}); pp.on('pageerror', lambda e: erreurs.append(str(e)))
    pp.goto(URL + '?niveau=pilotage'); pp.wait_for_selector('.mg-grille')
    verifier('pilotage : écrans sans charge vécue', pp.locator('[data-ecran]').count() == 3 and pp.locator('[data-ecran]', has_text='Charge').count() == 0)
    verifier('pilotage : escalades et arbitrages seulement (2)', pp.locator('.mg-signalement').count() == 2 and pp.get_by_text('Imprimante du 2e').count() == 0)
    verifier('pilotage : demande d\'arbitrage signalée', pp.locator('.mg-signalement', has_text='Priorité entre la campagne').locator('.fr-badge', has_text='Arbitrage').count() == 1)
    verifier('pilotage : tension par équipe et par semaine', pp.locator('.mg-zone--tensions tbody tr').count() == 2)
    txt = pp.locator('#mg-app').inner_text()
    verifier('pilotage : jamais de réponse individuelle sur la charge', 'Trop d\'appels' not in txt and 'Camille Martin' not in txt and 'Charge vécue' not in txt)
    verifier('pilotage : aucune priorité ni météo d\'équipe', pp.locator('.mg-priorite').count() == 0 and pp.locator('.mg-zone--meteo').count() == 0)
    pp.screenshot(path='/tmp/mg-pilotage.png', full_page=True); pp.close()
    verifier('aucune erreur JavaScript', not erreurs)
    if erreurs: print(erreurs)
    b.close()
print(f'{ok} réussis, {ko} échoués'); sys.exit(1 if ko else 0)
